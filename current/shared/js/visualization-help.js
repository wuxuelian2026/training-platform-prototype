export function mountDashboardHelp() {
  const trigger = document.getElementById('dashboard-help');
  if (!trigger) return;
  const dialog = document.createElement('dialog');
  dialog.className = 'dashboard-help-dialog';
  dialog.setAttribute('aria-labelledby', 'dashboard-help-title');
  const header = document.createElement('header');
  header.innerHTML = '<h2 id="dashboard-help-title">培训驾驶舱 · 页面说明</h2>';
  const close = document.createElement('button');
  close.type = 'button';
  close.className = 'icon-button';
  close.setAttribute('aria-label', '关闭说明');
  close.title = '关闭说明';
  close.append(createElement(X, { 'aria-hidden': 'true' }));
  header.append(close);
  const content = document.createElement('div');
  content.className = 'dashboard-help-content';
  const note = document.createElement('p');
  note.textContent = '当前原型使用 visualization-data.js 的独立演示事实数据：班级、批次、课程、教师、报名、支付订单及完成退款。以下业务实体为统计来源映射，不表示已连接后台接口。全页统计全部校区，金额以分计算后转换展示。';
  content.append(note);
  const labels = ['指标定义', '数据来源', '计算公式', '业务规则', '交互效果'];
  sections.forEach(([title, indicators]) => {
    const section = document.createElement('section');
    const heading = document.createElement('h3');
    heading.textContent = title;
    section.append(heading);
    indicators.forEach(([name, ...details]) => {
      const subtitle = document.createElement('h4');
      subtitle.textContent = name;
      const list = document.createElement('dl');
      details.forEach((text, index) => {
        const term = document.createElement('dt');
        term.textContent = labels[index];
        const description = document.createElement('dd');
        description.textContent = text;
        list.append(term, description);
      });
      section.append(subtitle, list);
    });
    content.append(section);
  });
  dialog.append(header, content);
  document.querySelector('.dashboard-screen').append(dialog);
  trigger.addEventListener('click', () => { content.scrollTop = 0; dialog.showModal(); });
  close.addEventListener('click', () => dialog.close());
  dialog.addEventListener('click', event => { if (event.target === dialog) dialog.close(); });
}
